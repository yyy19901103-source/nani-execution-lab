export type Contribution = 'entry' | 'core' | 'edge' | 'advanced';

export type Purpose =
  | 'downtime'
  | 'inventory'
  | 'maintenance'
  | 'quality'
  | 'safety'
  | 'traceability'
  | 'energy'
  | 'productivity';

export type StudentLevel = 'ok' | 'partial' | 'no';

